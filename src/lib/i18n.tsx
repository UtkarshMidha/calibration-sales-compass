export type MsgKey = keyof Messages;
const CATALOG = { de, en };

export type TFn = (key: MsgKey, vars?: Record<string, string | number>) => string;

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

export function makeT(lang: Lang): TFn {
  const dict = CATALOG[lang] as Record<string, string>;
  const fallback = de as Record<string, string>;
  return (key, vars) => interpolate(dict[key] ?? fallback[key] ?? key, vars);
}

